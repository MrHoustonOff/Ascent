func pick(seed string, xs []string) string {
	if len(xs) == 0 {
		return ""
	}
	h := fnv.New32a()
	h.Write([]byte(seed))
	return xs[int(h.Sum32())%len(xs)]
}

// motd — одна спокойная фраза на сегодня.
func (s *snap) motd() string {
	in := s.in
	day := s.today.Format("2006-01-02")
	nl := in.NextLesson()
	if nl == nil {
		return "Весь путь пройден. Дальше — факультатив «К мидлу», когда захочется."
	}
	days := in.ActiveDays()
	if len(days) == 0 {
		return "Первый урок займёт совсем немного. Остальное придёт само."
	}
	// пауза: последние три дня без учёбы и без отдыха
	gap := 0
	for d := s.today.AddDate(0, 0, -1); gap < 30; d = d.AddDate(0, 0, -1) {
		k := d.Format("2006-01-02")
		if days[k] || in.Rest[k] {
			break
		}
		gap++
	}
	if gap >= 3 && !days[day] {
		title := nl.Title
		if th := s.a.plan.Themes[nl.Theme]; th != nil {
			title = th.Title
		}
		return fmt.Sprintf("С возвращением. Продолжим с темы «%s» — ничего не потеряно.", strings.ReplaceAll(title, "`", ""))
	}
	streak := stats.CurrentStreak(days, in.Rest, s.today)
	var cands []string
	if nl.Kind == "run" {
		return motdRun[0]
	}
	// тематическое — главное, поэтому дважды
	if xs := motdBlock[nl.Block]; len(xs) > 0 {
		cands = append(cands, xs...)
		cands = append(cands, xs...)
	}
	h := s.now.In(s.a.Loc).Hour()
	part := "night"
	switch {
	case h >= 5 && h < 12:
		part = "morning"
	case h >= 12 && h < 18:
		part = "day"
	case h >= 18 && h < 23:
		part = "evening"
	}
	cands = append(cands, motdPart[part]...)
	cands = append(cands, motdWeekday[int(s.today.Weekday())]...)
	switch {
	case streak >= 30:
		cands = append(cands, fmt.Sprintf("%d дней подряд. Это уже часть вашей жизни.", streak))
	case streak >= 7:
		cands = append(cands, fmt.Sprintf("Серия — %d %s. Ровный ритм работает лучше рывков.", streak, plural(streak, "день", "дня", "дней")))
	}
	done, total := s.totalCounts()
	if p := pct(done, total); p >= 50 && p < 100 {
		cands = append(cands, fmt.Sprintf("Пройдено %d %% пути. Больше половины позади.", p))
	}
	return pick(day+part, cands)
}
